#!/bin/sh
# Deploy the sway-tablet dotfiles to a device.
#
# The config/ tree mirrors absolute on-device paths, so this is a plain copy.
#
#   ./install.sh [--user NAME] [--home DIR] [--dry-run] [--no-swaymsg]
set -eu

REPO=$(cd "$(dirname "$0")" && pwd)
USER_NAME=${SUDO_USER:-${USER:-$(id -un)}}
HOME_DIR=
DRY_RUN=0
RELOAD=1

while [ $# -gt 0 ]; do
    case "$1" in
        --user)     USER_NAME=$2; shift 2 ;;
        --home)     HOME_DIR=$2; shift 2 ;;
        --dry-run)  DRY_RUN=1; shift ;;
        --no-swaymsg) RELOAD=0; shift ;;
        -h|--help)  sed -n '2,10p' "$0"; exit 0 ;;
        *) echo "unknown option: $1" >&2; exit 2 ;;
    esac
done

# Do not deploy into /root by accident, and never run the copy as root unless
# an explicit target user/home was given (or we can infer it from sudo).
if [ "$(id -u)" = 0 ] && [ "$DRY_RUN" = 0 ] && [ "$USER_NAME" = root ] \
        && [ -z "$HOME_DIR" ] && [ -z "${SUDO_USER:-}" ]; then
    echo "run as the target user, or pass --user NAME / --home DIR" >&2
    exit 1
fi

if [ -z "$HOME_DIR" ]; then
    if [ "$(id -un)" = "$USER_NAME" ]; then
        HOME_DIR=$HOME
    else
        HOME_DIR=$(getent passwd "$USER_NAME" | cut -d: -f6)
    fi
fi

[ -d "$HOME_DIR" ] || { echo "home dir not found: $HOME_DIR" >&2; exit 1; }

SRC=$REPO/config/home

run() {
    if [ "$DRY_RUN" = 1 ]; then
        echo "  $*"
    else
        "$@"
    fi
}

echo "deploying sway-tablet -> $HOME_DIR (user $USER_NAME)"

# 1. application config (sway, waybar, pipewire)
#
# accent, accent.conf and style.css are generated by accent-update; install the
# shipped defaults only when the file does not exist yet, so re-running this
# script does not silently throw away the user's wallpaper-derived theme.
KEEP="sway/accent,sway/accent.conf,waybar/style.css"
for d in sway waybar pipewire; do
    [ -d "$SRC/.config/$d" ] || continue
    run mkdir -p "$HOME_DIR/.config/$d"
    for f in "$SRC/.config/$d"/*; do
        [ -e "$f" ] || continue
        base=$(basename "$f")
        case ",$KEEP," in
            *",$d/$base,"*)
                if [ -e "$HOME_DIR/.config/$d/$base" ]; then
                    echo "  keeping existing $d/$base"
                    continue
                fi
                ;;
        esac
        run cp -a --no-preserve=ownership "$f" "$HOME_DIR/.config/$d/$base"
    done
done

# 2. helper scripts
run mkdir -p "$HOME_DIR/.local/bin"
for f in "$SRC/.local/bin"/*; do
    [ -f "$f" ] || continue
    # remove first: overwriting a running binary fails with ETXTBSY
    run rm -f "$HOME_DIR/.local/bin/$(basename "$f")"
    run cp -a --no-preserve=ownership "$f" "$HOME_DIR/.local/bin/"
    run chmod +x "$HOME_DIR/.local/bin/$(basename "$f")"
done

# 3. desktop entries
if [ -d "$SRC/.local/share/applications" ]; then
    run mkdir -p "$HOME_DIR/.local/share/applications"
    for f in "$SRC/.local/share/applications"/*.desktop; do
        [ -f "$f" ] || continue
        run cp -a --no-preserve=ownership "$f" "$HOME_DIR/.local/share/applications/"
    done
fi

# when invoked through sudo, hand the deployed files back to the target user
if [ "$DRY_RUN" = 0 ] && [ "$(id -u)" = 0 ]; then
    run chown -R "$USER_NAME": "$HOME_DIR/.config/sway" "$HOME_DIR/.config/waybar" \
        "$HOME_DIR/.config/pipewire" "$HOME_DIR/.local/bin" 2>/dev/null || true
fi

echo "done"

if [ "$DRY_RUN" = 0 ] && [ "$(id -u)" != 0 ] && [ "$RELOAD" = 1 ] \
        && command -v swaymsg >/dev/null 2>&1; then
    echo "reloading sway"
    swaymsg reload || echo "  (swaymsg failed - log out and back in)"
fi

cat <<'EOF'

next steps
  1. start a session:  sway   (or see docs/01-desktop-sway.md for
     "boot straight into sway" with getty autologin / a systemd user unit)
  2. accent theme:  ~/.local/bin/accent-update
  3. the on-screen keyboard and the panel start automatically via autostart.sh
EOF
